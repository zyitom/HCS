/// 由拟合表求 4×10 增益矩阵（Helios lqr_K）。
inline void lqr_k(double left_length, double right_length,
                  const double k_fit[40][6], double k_matrix[4][10]) {
    const double cross = left_length * right_length;
    const double left_squared = left_length * left_length;
    const double right_squared = right_length * right_length;
    for (std::size_t row = 0; row < 4; ++row)
        for (std::size_t col = 0; col < 10; ++col) {
            const auto& c = k_fit[col * 4 + row];
            k_matrix[row][col] = c[0] + c[1] * left_length + c[2] * right_length
                               + c[3] * left_squared + c[4] * cross + c[5] * right_squared;
        }
}

/// A 矩阵的 16 个稀疏动态行（num = col*10 + row），其余元素为零。
inline constexpr bool is_sparse_a_entry(std::size_t num) {
    constexpr std::size_t kDynamicRows[16] = {10, 32, 41, 43, 45, 47, 49, 54,
                                              61, 63, 65, 67, 69, 76, 89, 98};
    for (const auto dynamic : kDynamicRows)
        if (num == dynamic)
            return true;
    return false;
}

/// 由拟合表求 10×10 A 矩阵（Helios lqr_A，只填 16 个非零项）。
inline void lqr_a(double left_length, double right_length,
                  const double a_fit[100][6], double a_matrix[10][10]) {
    for (std::size_t i = 0; i < 10; ++i)
        for (std::size_t j = 0; j < 10; ++j)
            a_matrix[i][j] = 0.0;
    const double cross = left_length * right_length;
    const double left_squared = left_length * left_length;
    const double right_squared = right_length * right_length;
    for (std::size_t row = 0; row < 10; ++row)
        for (std::size_t col = 0; col < 10; ++col) {
            const std::size_t num = col * 10 + row;
            if (!is_sparse_a_entry(num))
                continue;
            const auto& c = a_fit[num];
            a_matrix[row][col] = c[0] + c[1] * left_length + c[2] * right_length
                               + c[3] * left_squared + c[4] * cross + c[5] * right_squared;
        }
}

/// 由拟合表求 10×4 B 矩阵（Helios lqr_B，只填奇数行）。
inline void lqr_b(double left_length, double right_length,
                  const double b_fit[40][6], double b_matrix[10][4]) {
    for (std::size_t i = 0; i < 10; ++i)
        for (std::size_t j = 0; j < 4; ++j)
            b_matrix[i][j] = 0.0;
    const double cross = left_length * right_length;
    const double left_squared = left_length * left_length;
    const double right_squared = right_length * right_length;
    for (std::size_t row = 0; row < 10; ++row)
        for (std::size_t col = 0; col < 4; ++col) {
            const std::size_t num = col * 10 + row;
            if (num % 2 == 0)
                continue;
            const auto& c = b_fit[col * 10 + row];
            b_matrix[row][col] = c[0] + c[1] * left_length + c[2] * right_length
                               + c[3] * left_squared + c[4] * cross + c[5] * right_squared;
        }
}

/// K·x 的四通道输出。某腿离地时该腿轮矩清零、髋矩只保留腿角通道 ×improve0
///（Helios calculate_status_vector_fly）。
inline void lqr_torques(const double k_matrix[4][10], const double state[10],
                        double& wheel_left, double& wheel_right, double& hip_left,
                        double& hip_right, bool leg_off_ground_left, bool leg_off_ground_right,
                        double improve0) {
    const auto dot = [&](std::size_t row) {
        double value = 0.0;
        for (std::size_t col = 0; col < 10; ++col)
            value += k_matrix[row][col] * state[col];
        return value;
    };

    if (leg_off_ground_left) {
        wheel_left = 0.0;
        hip_left = (k_matrix[2][4] * state[4] + k_matrix[2][5] * state[5]) * improve0;
    } else {
        wheel_left = dot(0);
        hip_left = dot(2);
    }
    if (leg_off_ground_right) {
        wheel_right = 0.0;
        hip_right = (k_matrix[3][6] * state[6] + k_matrix[3][7] * state[7]) * improve0;
    } else {
        wheel_right = dot(1);
        hip_right = dot(3);
    }
}

