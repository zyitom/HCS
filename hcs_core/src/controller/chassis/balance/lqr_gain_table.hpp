// LQR 拟合增益表，数值逐项取自 Helios
// User_Code/user/balance/balance_def.hpp 的 K_out / A_out / B_out（行号
// 292-332 / 333-433 / 434-474），未作任何修改。
//
// 每行 6 个系数是二元二次多项式 f(LL, LR) = c0 + c1·LL + c2·LR + c3·LL² +
// c4·LL·LR + c5·LR²，自变量为左右腿长 [m]。
//   - K：4×10 增益，系数行索引 = col*4 + row（q_diag=[5,300,300,10,40000,18,
//     40000,18,17000,24]，r_diag=[1,1,0.25,0.25]，见 balance_def.hpp 表底注释）；
//   - A：10×10 稀疏，只有 16 个动态行有值（num = col*10 + row）；
//   - B：10×4，只有奇数行有值。
//
// 状态向量序（与 Helios lqr_matrix.Status_vector 一致）：
//   [0] 位置参考 [1] 速度误差 [2] yaw 误差 [3] yaw 速率
//   [4]/[5] 左腿角/角速率 [6]/[7] 右腿角/角速率
//   [8]/[9] 机体俯仰/俯仰速率
// 控制向量：[0] 左轮矩 [1] 右轮矩 [2] 左髋矩 [3] 右髋矩。
// ============================================================================

